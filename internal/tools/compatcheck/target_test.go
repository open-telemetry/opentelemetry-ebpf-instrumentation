package main

import (
	"io"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestTargetBPFArtifacts(t *testing.T) {
	const binding = "// Code generated by bpf2go; DO NOT EDIT.\npackage public; type Event struct{}\n"
	for _, tc := range []struct {
		name, source, existing, wantError string
	}{
		{name: "generated binding", source: binding},
		{name: "handwritten source", source: "package public", wantError: "no bpf2go generator header"},
		{name: "tracked source preserved", source: binding, existing: "package public; func Stable() {}", wantError: "file exists"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			artifacts, target := t.TempDir(), t.TempDir()
			rel := filepath.Join("pkg/public", "bindings_generated.go")
			writeFile(t, filepath.Join(artifacts, rel), tc.source)
			if tc.existing != "" {
				writeFile(t, filepath.Join(target, rel), tc.existing)
			}
			err := prepareTargetBPF(t.Context(), target, artifacts, "amd64", io.Discard)
			if tc.wantError != "" {
				if err == nil || !strings.Contains(err.Error(), tc.wantError) {
					t.Fatalf("error=%v, want %s", err, tc.wantError)
				}
			} else if err != nil {
				t.Fatal(err)
			}
			if tc.existing != "" || tc.wantError == "" {
				data, err := os.ReadFile(filepath.Join(target, rel))
				want := tc.source
				if tc.existing != "" {
					want = tc.existing
				}
				if err != nil || string(data) != want {
					t.Fatalf("target=%q, %v; want %q", data, err, want)
				}
			}
		})
	}
}
