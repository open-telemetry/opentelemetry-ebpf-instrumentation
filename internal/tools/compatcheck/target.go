package main

import (
	"bytes"
	"context"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

func prepareTargetBPF(ctx context.Context, target, artifacts, architectures string, progress io.Writer) error {
	if artifacts == "" {
		fmt.Fprintln(progress, "Generating target BPF artifacts")
		cmd := exec.CommandContext(ctx, "make", "docker-generate", "BPF_TARGETS="+architectures)
		cmd.Dir = target
		cmd.Stdout, cmd.Stderr = progress, progress
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("generate target BPF artifacts: %w", err)
		}
		return nil
	}
	if err := filepath.WalkDir(artifacts, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		if !entry.Type().IsRegular() {
			return fmt.Errorf("unsupported BPF artifact %s", path)
		}
		binding := path
		switch filepath.Ext(path) {
		case ".go":
		case ".o":
			binding = strings.TrimSuffix(path, ".o") + ".go"
		default:
			return fmt.Errorf("unsupported BPF artifact %s", path)
		}
		data, err := os.ReadFile(binding)
		if err != nil {
			return err
		}
		if !bytes.HasPrefix(data, []byte("// Code generated by bpf2go; DO NOT EDIT.")) {
			return fmt.Errorf("BPF artifact %s has no bpf2go generator header", binding)
		}
		return nil
	}); err != nil {
		return err
	}
	// CopyFS refuses to overwrite the target revision's tracked source files.
	return os.CopyFS(target, os.DirFS(artifacts))
}
